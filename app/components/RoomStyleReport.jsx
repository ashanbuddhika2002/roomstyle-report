/* ============================================================
   VAULT PERSISTENCE
   Now that this is deployed on a real domain (not previewed inside
   a Claude Artifact, where storage APIs fail silently), this uses
   real localStorage — guarded so it degrades safely to an in-memory
   fallback if storage is unavailable or the environment briefly
   server-renders this component before hydration.

   RESULT_SCHEMA_VERSION exists because a saved result's shape has
   changed across rounds of this build (gapItems and colorNames were
   added later). Without validation, an old saved entry missing those
   fields would throw when clicked instead of failing safely — this
   is a real bug from the previous version, not a hypothetical one.
   Old/incompatible entries are simply discarded rather than migrated,
   which is the right tradeoff for a small "last 4 reports" cache.
   ============================================================ */
const RESULT_SCHEMA_VERSION = 1;

function isValidResult(r) {
  return (
    r &&
    r.version === RESULT_SCHEMA_VERSION &&
    Array.isArray(r.scored) &&
    Array.isArray(r.gapItems) &&
    Array.isArray(r.colorNames) &&
    Array.isArray(r.swatches) &&
    typeof r.variance === "number" &&
    typeof r.baseCohesion === "number" &&
    typeof r.roomTypeLabel === "string"
  );
}

let memoryVault = [];
function vaultGet() {
  try {
    if (typeof window === "undefined" || !window.localStorage) {
      return memoryVault.filter(isValidResult);
    }
    const raw = window.localStorage.getItem("stylevault_vault");
    const parsed = raw ? JSON.parse(raw) : [];
    return Array.isArray(parsed) ? parsed.filter(isValidResult) : [];
  } catch (e) {
    return memoryVault.filter(isValidResult);
  }
}
function vaultSet(entries) {
  memoryVault = entries;
  try {
    if (typeof window === "undefined" || !window.localStorage) return;
    window.localStorage.setItem("stylevault_vault", JSON.stringify(entries));
  } catch (e) {
    /* quota exceeded or unavailable — in-memory value above still holds */
  }
}

