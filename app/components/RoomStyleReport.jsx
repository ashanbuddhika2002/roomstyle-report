// Prevents the same name (e.g. "Espresso") appearing twice in one report —
// each swatch is matched in turn, skipping names already claimed.
function uniqueColorNames(swatches) {
  const used = new Set();
  return swatches.map((c) => {
    let best = null, bestDist = Infinity;
    NAMED_COLORS.forEach(([name, nr, ng, nb]) => {
      if (used.has(name)) return;
      const d = (c.r - nr) ** 2 + (c.g - ng) ** 2 + (c.b - nb) ** 2;
      if (d < bestDist) { bestDist = d; best = name; }
    });
    if (!best) best = "Neutral";
    used.add(best);
    return best;
  });
}

