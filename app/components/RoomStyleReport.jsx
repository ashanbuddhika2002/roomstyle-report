function bucketSwatch(bucket) {
  const s = Math.min(70, Math.round(bucket.idealSat * 140));
  const l = Math.round(38 + bucket.idealLight * 38);
  return `hsl(${Math.round(bucket.idealHue)}, ${s}%, ${l}%)`;
}

// Deterministic, room-aware, genuinely impact-ranked — no shuffle. Every
// genuinely room-relevant item is shown first, ranked by impact; only the
// remaining empty slots (if any) are backfilled from the general pool.
// The previous version discarded room-relevance entirely the moment a
// room+style combination had fewer than 5 tagged items, which could
// recommend a bed frame in a bathroom report — this version never drops
// a relevant item to make room for an irrelevant one.
function selectGapItems(bucket, roomId) {
  const fullPool = bucket.gapPool;
  const eligible = roomId ? fullPool.filter((item) => item.rooms.includes(roomId)) : fullPool;
  const sortedEligible = [...eligible].sort(
    (a, b) => b.i - a.i || fullPool.indexOf(a) - fullPool.indexOf(b)
  );
  if (sortedEligible.length >= 5) return sortedEligible.slice(0, 5);

  const usedTexts = new Set(sortedEligible.map((it) => it.t));
  const backfill = fullPool
    .filter((it) => !usedTexts.has(it.t))
    .sort((a, b) => b.i - a.i || fullPool.indexOf(a) - fullPool.indexOf(b));
  return [...sortedEligible, ...backfill].slice(0, 5);
}

